-- Supabase-skjema for OBOS Tabell-tipper 2026
-- Dette skriptet kan trygt kjøres én eller flere ganger i Supabase SQL Editor.

-- 1. Tips-tabell
create table if not exists public.tips (
  id text primary key,
  author text not null,
  user_email text default '',
  table_data jsonb not null,
  updated_at timestamptz default now()
);

-- Sikre at kolonnen 'user_email' finnes hvis tabellen allerede var opprettet
alter table public.tips add column if not exists user_email text default '';

-- 2. Fasit-tabell (én rad med id = 'current')
create table if not exists public.fasit (
  id text primary key,
  table_data jsonb not null,
  updated_at timestamptz default now()
);

-- 3. Brukere (Registrerte deltakere med Kallenavn og E-post)
create table if not exists public.users (
  email text primary key,
  nickname text not null,
  created_at timestamptz default now(),
  last_active timestamptz default now()
);

-- 4. Hendelseslogg (Audit-logg over hvem som logger inn eller lagrer tips)
create table if not exists public.user_logs (
  id bigint generated by default as identity primary key,
  user_email text not null,
  nickname text not null,
  action text not null, -- f.eks. 'LOGIN', 'SAVE_TIP'
  created_at timestamptz default now()
);

-- 5. Aktiver Row Level Security (RLS)
alter table public.tips enable row level security;
alter table public.fasit enable row level security;
alter table public.users enable row level security;
alter table public.user_logs enable row level security;

-- 6. Tillat anonym lesing/skriving via Supabase anon-nøkkel (Idempotente policyer)
drop policy if exists "Allow anon read tips" on public.tips;
drop policy if exists "Allow anon insert tips" on public.tips;
drop policy if exists "Allow anon update tips" on public.tips;
drop policy if exists "Allow anon delete tips" on public.tips;
create policy "Allow anon read tips" on public.tips for select using (true);
create policy "Allow anon insert tips" on public.tips for insert with check (true);
create policy "Allow anon update tips" on public.tips for update using (true);
create policy "Allow anon delete tips" on public.tips for delete using (true);

drop policy if exists "Allow anon read fasit" on public.fasit;
drop policy if exists "Allow anon insert fasit" on public.fasit;
drop policy if exists "Allow anon update fasit" on public.fasit;
create policy "Allow anon read fasit" on public.fasit for select using (true);
create policy "Allow anon insert fasit" on public.fasit for insert with check (true);
create policy "Allow anon update fasit" on public.fasit for update using (true);

drop policy if exists "Allow anon read users" on public.users;
drop policy if exists "Allow anon insert users" on public.users;
drop policy if exists "Allow anon update users" on public.users;
drop policy if exists "Allow anon delete users" on public.users;
create policy "Allow anon read users" on public.users for select using (true);
create policy "Allow anon insert users" on public.users for insert with check (true);
create policy "Allow anon update users" on public.users for update using (true);
create policy "Allow anon delete users" on public.users for delete using (true);

drop policy if exists "Allow anon read user_logs" on public.user_logs;
drop policy if exists "Allow anon insert user_logs" on public.user_logs;
create policy "Allow anon read user_logs" on public.user_logs for select using (true);
create policy "Allow anon insert user_logs" on public.user_logs for insert with check (true);

-- 7. Duplikatbeskyttelse: Unike indekser for kallenavn og e-post (case-insensitive)
create unique index if not exists users_unique_lower_nickname 
on public.users (lower(trim(nickname)));

create unique index if not exists tips_unique_lower_author 
on public.tips (lower(trim(author)));

create unique index if not exists tips_unique_lower_email 
on public.tips (lower(trim(user_email))) 
where user_email is not null and user_email != '';
